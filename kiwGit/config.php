function initDirectories() {
    $dirs = [REPO_PATH, LOG_PATH, TMP_PATH];
    foreach ($dirs as $dir) {
        if (!is_dir($dir)) {
            mkdir($dir, 0755, true);
            @chmod($dir, 0755);
        }
    }
}

// Инициализация
initDirectories();

