function logMessage($message, $type = 'info') {
    $logFile = LOG_PATH . '/' . date('Y-m-d') . '.log';
    $timestamp = date('Y-m-d H:i:s');
    $entry = "[$timestamp] [$type] $message" . PHP_EOL;
    file_put_contents($logFile, $entry, FILE_APPEND);
}

// ============================================================
// ПРОВЕРКА РАЗРЕШЁННЫХ РАСШИРЕНИЙ
// ============================================================

function isExtensionAllowed($filename) {
    $ext = strtolower(pathinfo($filename, PATHINFO_EXTENSION));
    
    // Если расширения не разрешены — разрешаем все
    if (empty(ALLOWED_EXTENSIONS)) {
        return !in_array($ext, FORBIDDEN_EXTENSIONS);
    }
    
    return in_array($ext, ALLOWED_EXTENSIONS);
}

// ============================================================
// ВАЛИДАЦИЯ ИМЕНИ РЕПОЗИТОРИЯ
// ============================================================

function isValidRepoName($name) {
    return (bool) preg_match('/^[a-zA-Z0-9_\-\.]+$/', $name);
}

function isValidBranchName($name) {
    return (bool) preg_match('/^[a-zA-Z0-9_\-\.\/]+$/', $name);
}

// ============================================================
// ФУНКЦИЯ ДЛЯ ПОЛУЧЕНИЯ СПИСКА РЕПОЗИТОРИЕВ (для других файлов)
// ============================================================

function getRepositories() {
    $repos = [];
    if (!is_dir(REPO_PATH)) return $repos;
    
    $dirs = scandir(REPO_PATH);
    foreach ($dirs as $dir) {
        if ($dir === '.' || $dir === '..') continue;
        $fullPath = REPO_PATH . '/' . $dir;
        if (is_dir($fullPath) && file_exists($fullPath . '/.gkit')) {
            $repos[] = $dir;
        }
    }
    return $repos;
}